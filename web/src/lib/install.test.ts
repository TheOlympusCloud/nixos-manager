import { describe, expect, it } from 'vitest'
import { addressProblem, diskOf, installCommand, isPlaceholder } from './install'
import { previewFiles } from './machines'

describe('addressProblem', () => {
  it('takes host names and IPv4 addresses only, as they go into a shell command and nix copy', () => {
    for (const ok of ['', '192.168.1.50', 'nas', 'nas.lan', 'my-pc.example.org']) expect(addressProblem(ok), ok).toBe('')
    for (const v6 of ['fe80::1', '2001:db8::7', '[2001:db8::7]']) expect(addressProblem(v6), v6).toMatch(/IPv6/)
    for (const bad of ['root@nas', 'nas;reboot', 'nas $(id)', '-oProxyCommand=x', 'nas:22', 'a..b', 'nas.', '`x`', "nas'", 'nas\nx']) expect(addressProblem(bad), bad).not.toBe('')
  })
})

describe('installCommand', () => {
  it('generates the hardware configuration, then commits and pushes it', () => {
    expect(installCommand('nas', '192.168.1.50', true)).toBe(
      'git pull --ff-only && nix run github:nix-community/nixos-anywhere -- --flake .#nas --target-host root@192.168.1.50 --copy-host-keys' +
        ' --generate-hardware-config nixos-generate-config ./hosts/nas/hardware-configuration.nix &&' +
        ' git commit -m "nas: hardware configuration from nixos-anywhere" -- hosts/nas/hardware-configuration.nix && git push',
    )
  })
  it('keeps a hardware configuration the repository has', () => {
    expect(installCommand('nas', 'nas.lan', false)).toBe('git pull --ff-only && nix run github:nix-community/nixos-anywhere -- --flake .#nas --target-host root@nas.lan --copy-host-keys')
  })
  it('never puts an unchecked address in the command', () => {
    expect(installCommand('nas', '', false)).toContain('root@<address>')
    expect(installCommand('nas', 'nas; rm -rf ~', true)).toContain('root@<address>')
    expect(installCommand('nas', 'nas; rm -rf ~', true)).not.toContain('rm -rf')
  })
})

describe('diskOf and isPlaceholder', () => {
  const files = (system: 'x86_64-linux' | 'aarch64-linux') =>
    previewFiles({ name: 'nas', system, role: 'minimal', disk: 'ext4', device: '/dev/disk/by-id/nvme-x' })
  it('reads the disk of the layouts the wizard writes', () => {
    // aarch64's boot loader has device = "nodev" before the disk.
    for (const s of ['x86_64-linux', 'aarch64-linux'] as const) expect(diskOf(files(s)[2].content)).toBe('/dev/disk/by-id/nvme-x')
    expect(diskOf('{ }')).toBe('')
  })
  it('knows the placeholders from a real hardware configuration', () => {
    expect(isPlaceholder(files('x86_64-linux')[1].content)).toBe(true)
    expect(isPlaceholder(previewFiles({ name: 'nas', system: 'x86_64-linux', role: 'minimal' })[1].content)).toBe(true)
    expect(isPlaceholder('# Do not modify this file!  It was generated by ‘nixos-generate-config’\n{ }')).toBe(false)
  })
})
